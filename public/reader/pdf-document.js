// Keep the original reading-order text for Morningstar, and retain positioned
// text for column-aware report formats. Never flatten a table across columns.
export function positionedLines(items, region = {}) {
  const selected = items.filter(item => item.text.trim()
    && item.x >= (region.left ?? -Infinity) && item.x < (region.right ?? Infinity)
    && item.y >= (region.top ?? -Infinity) && item.y < (region.bottom ?? Infinity));
  const lines = [];
  for (const item of [...selected].sort((a, b) => a.y - b.y || a.x - b.x)) {
    let line = lines.findLast(value => Math.abs(value.y - item.y) < 2);
    if (!line) { line = { y: item.y, items: [] }; lines.push(line); }
    line.items.push(item);
  }
  return lines.map(line => {
    line.items.sort((a, b) => a.x - b.x);
    let text = "", last = null;
    for (const item of line.items) {
      if (last && item.x - last.x - last.width > 1 && !/\s$/.test(text)) text += " ";
      text += item.text;
      last = item;
    }
    return { ...line, text: text.replace(/\s+/g, " ").trim() };
  });
}

export async function extractPdfDocument(pdfjs, data, onProgress = () => {}) {
  const loading = pdfjs.getDocument({ data: new Uint8Array(data), isEvalSupported: false, useWorkerFetch: false });
  const pages = [], plainPages = [];
  try {
    const pdf = await loading.promise;
    for (let pageNumber = 1; pageNumber <= pdf.numPages; pageNumber++) {
      onProgress(pageNumber, pdf.numPages);
      const page = await pdf.getPage(pageNumber);
      const viewport = page.getViewport({ scale: 1 });
      const content = await page.getTextContent();
      const items = [], lines = [];
      let current = "", lastY = null;
      for (const item of content.items) {
        if (!("str" in item) || !item.str.trim()) continue;
        const matrix = pdfjs.Util.transform(viewport.transform, item.transform);
        items.push({ text: item.str, x: matrix[4], y: matrix[5], width: item.width, height: item.height, font: item.fontName });
        const y = item.transform?.[5] ?? lastY;
        const startsNewLine = item.hasEOL || (lastY !== null && y !== null && Math.abs(y - lastY) > 3.5);
        if (startsNewLine && current.trim()) { lines.push(current.trim()); current = ""; }
        current += `${current ? " " : ""}${item.str}`;
        lastY = y;
        if (item.hasEOL && current.trim()) { lines.push(current.trim()); current = ""; }
      }
      if (current.trim()) lines.push(current.trim());
      // Some providers label forecasts by the fill of chart bars. Keep the
      // painted rectangles so the parser can read the document's own legend.
      // No provider colour or calendar cutoff is embedded here.
      const rectangles = /Estimate|Argus Recommendations/i.test(lines.join(' '))
        ? await extractRectangles(pdfjs, page, viewport) : [];
      pages.push({ number: pageNumber, width: viewport.width, height: viewport.height, items, lines: positionedLines(items), rectangles });
      plainPages.push(`[[PAGE ${pageNumber} OF ${pdf.numPages}]]\n${lines.join("\n")}`);
      page.cleanup();
    }
    const missingPages=pages.filter(p=>!p.items.length).map(p=>p.number);
    const textCoverage={missingPages,readablePages:pages.length-missingPages.length};
    return { text: plainPages.join("\n\n"), pages, pageCount: pdf.numPages, textCoverage };
  } finally { await loading.destroy(); }
}

// Page markers are generated by our code and must not count as readable PDF text.
export function missingPageNote(coverage){
  const p=coverage?.missingPages||[];if(!p.length)return '';
  const runs=[];for(const n of p){const r=runs.at(-1);if(r&&r[1]+1===n)r[1]=n;else runs.push([n,n]);}
  const pages=runs.map(([a,b])=>a===b?String(a):a+'–'+b).join(', ');
  return (p.length===1?'Page '+pages+' has':'Pages '+pages+' have')+' no selectable text. Check the original PDF.';
}
export function pdfOpenMessage(error,name){
  if(error?.name==='PasswordException')return name+' requires a PDF password. Choose a copy from the publisher that opens without a password.';
  if(error?.name==='InvalidPDFException')return name+' could not be opened as a PDF. Download the original report again and select the new file.';
  return null;
}

async function extractRectangles(pdfjs, page, viewport) {
  const ops = await page.getOperatorList();
  const stack = [], rects = [];
  let state = { matrix: [1, 0, 0, 1, 0, 0], color: '#000000', alpha: 1 };
  for (let i = 0; i < ops.fnArray.length; i++) {
    const op = ops.fnArray[i], args = ops.argsArray[i];
    if (op === pdfjs.OPS.save || op === pdfjs.OPS.paintFormXObjectBegin) {
      stack.push({ ...state, matrix: [...state.matrix] });
      if (op === pdfjs.OPS.paintFormXObjectBegin && args?.[0]) state.matrix = pdfjs.Util.transform(state.matrix, args[0]);
    } else if (op === pdfjs.OPS.restore || op === pdfjs.OPS.paintFormXObjectEnd) state = stack.pop() || state;
    else if (op === pdfjs.OPS.transform) state.matrix = pdfjs.Util.transform(state.matrix, args);
    else if (op === pdfjs.OPS.setFillRGBColor) state.color = typeof args[0] === 'string' ? args[0] : args.join(',');
    else if (op === pdfjs.OPS.setGState) { for (const [k, v] of args[0]) if (k === 'ca') state.alpha = v; }
    else if (op === pdfjs.OPS.constructPath && args[2] && [pdfjs.OPS.fill, pdfjs.OPS.eoFill, pdfjs.OPS.fillStroke, pdfjs.OPS.eoFillStroke].includes(args[0])) {
      const p = args[1]?.[0], b = args[2];
      // PDF.js compact path: move, straight edges, close. Curves are not bars.
      if (!p || p.length > 16) continue;
      const transform = pdfjs.Util.transform(viewport.transform, state.matrix);
      const point = (x, y) => [transform[0] * x + transform[2] * y + transform[4], transform[1] * x + transform[3] * y + transform[5]];
      const a = point(b[0], b[1]), z = point(b[2], b[3]);
      rects.push({ left: Math.min(a[0], z[0]), right: Math.max(a[0], z[0]), top: Math.min(a[1], z[1]), bottom: Math.max(a[1], z[1]), color: state.color, alpha: state.alpha });
    }
  }
  return rects;
}
